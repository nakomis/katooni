#!/usr/bin/env python3
"""Generate the firmware's screen assets: the boot splash and two bitmap fonts.

    python3 embedded/tools/make_assets.py --font /path/to/SourceCodePro-Bold.ttf

Writes, into embedded/main/assets/:
  logo_240.rgb565   docs/logo.png at 240×240, RGB565 big-endian (the ST7789's byte order)
  fonts.h           a small font for text (printable ASCII plus – − µ ≤ Ω) and a big one for the bag
                    letter (A–Z and ?), 1 bit per pixel, rows MSB first

Use an openly licensed font: Source Code Pro (SIL OFL 1.1) is what the committed assets came from.
The outputs are committed, so the firmware build doesn't need Pillow."""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "embedded" / "main" / "assets"
EXTRAS = "–−µ≤Ω"   # – − µ ≤ Ω
SMALL = (11, 20, 18)     # cell width, cell height, font size in px
BIG = (80, 112, 118)


def logo():
    img = Image.open(ROOT / "docs" / "logo.png").convert("RGB").resize((240, 240), Image.LANCZOS)
    out = bytearray()
    raw = img.tobytes()
    for i in range(0, len(raw), 3):
        r, g, b = raw[i], raw[i + 1], raw[i + 2]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((v >> 8, v & 0xFF))
    (OUT / "logo_240.rgb565").write_bytes(out)


def glyphs(font_path, cell, chars):
    w, h, size = cell
    font = ImageFont.truetype(str(font_path), size)
    # Centre the span from the top of a capital to the lowest descender in the cell.
    cap_top = font.getbbox("H")[1]
    bottom = max(font.getbbox(c)[3] for c in "gjpqyQ|_")
    top = (h - (bottom - cap_top)) // 2 - cap_top
    rows = []
    for ch in chars:
        img = Image.new("L", (w, h), 0)
        d = ImageDraw.Draw(img)
        bbox = d.textbbox((0, 0), ch, font=font)
        x = (w - (bbox[2] - bbox[0])) // 2 - bbox[0]
        d.text((x, top), ch, font=font, fill=255)
        if ch != " " and img.getbbox() is None:
            raise SystemExit(f"font has no glyph for {ch!r}")
        bits = []
        stride = (w + 7) // 8
        for y in range(h):
            row = [0] * stride
            for xx in range(w):
                if img.getpixel((xx, y)) >= 128:
                    row[xx // 8] |= 0x80 >> (xx % 8)
            bits += row
        rows.append((ch, bits))
    return rows


def c_font(name, cell, rows):
    w, h, _ = cell
    stride = (w + 7) // 8
    lines = [f"#define {name.upper()}_W {w}", f"#define {name.upper()}_H {h}",
             f"#define {name.upper()}_STRIDE {stride}", f"#define {name.upper()}_COUNT {len(rows)}",
             f"static const uint32_t {name}_codepoints[{len(rows)}] = {{"]
    lines.append("    " + ", ".join(f"0x{ord(c):04X}" for c, _ in rows) + ",")
    lines.append("};")
    lines.append(f"static const uint8_t {name}_bits[{len(rows)}][{stride * h}] = {{")
    for ch, bits in rows:
        lines.append(f"    /* U+{ord(ch):04X} */ {{" + ",".join(str(b) for b in bits) + "},")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", required=True, type=Path)
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    logo()
    small = glyphs(a.font, SMALL, [chr(c) for c in range(32, 127)] + list(EXTRAS))
    big = glyphs(a.font, BIG, [chr(c) for c in range(ord("A"), ord("Z") + 1)] + ["?"])
    (OUT / "fonts.h").write_text(
        "/* Generated by embedded/tools/make_assets.py from Source Code Pro Bold (SIL OFL 1.1). */\n"
        "#pragma once\n#include <stdint.h>\n\n" + c_font("font_small", SMALL, small) + "\n\n" +
        c_font("font_big", BIG, big) + "\n")
    print(f"wrote {OUT}/logo_240.rgb565 and {OUT}/fonts.h")


if __name__ == "__main__":
    main()
